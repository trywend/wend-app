import { build } from "esbuild";
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const entry = resolve(root, "editor-src/index.ts");
const generatedTs = resolve(root, "src/components/editor/markdownEditorHtml.generated.ts");
const previewHtml = resolve(root, "editor-src/preview.html");

const PAGE_CSS = `
*{box-sizing:border-box;}
html,body{margin:0;padding:0;background:transparent;}
#wend-editor{width:100%;}
.cm-editor{background:transparent;}
.cm-editor .cm-scroller{font-family:inherit;}
`.trim();

// Demo markdown for the standalone preview only (NOT bundled into the .ts artifact).
